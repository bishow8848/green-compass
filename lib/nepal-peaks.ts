const METRES_TO_FEET = 3.28084;

/** "8,849 m" — the label drawn next to the dot once the map is zoomed in. */
function metresLabel(elevation: number) {
  return `${elevation.toLocaleString("en-US")} m`;
}

export interface PeakFeatureProperties {
  name: string;
  altName: string;
  elevation: number;
  elevationFt: number;
  elevationLabel: string;
  region: string;
  kind: PeakKind;
  note: string;
  lng: number;
  lat: number;
}

/**
 * The same list as a GeoJSON FeatureCollection, ready to hand to a maplibre
 * `geojson` source. Every property the hover card needs is inlined so the
 * popup can be built straight from the queried feature.
 */
export const NEPAL_PEAKS_GEOJSON = {
  type: "FeatureCollection" as const,
  features: NEPAL_PEAKS.map((peak) => ({
    type: "Feature" as const,
    geometry: { type: "Point" as const, coordinates: [peak.lng, peak.lat] },
    properties: {
      name: peak.name,
      altName: peak.altName ?? "",
      elevation: peak.elevation,
      elevationFt: Math.round(peak.elevation * METRES_TO_FEET),
      elevationLabel: metresLabel(peak.elevation),
      region: peak.region,
      kind: peak.kind,
      note: peak.note ?? "",
      lng: peak.lng,
      lat: peak.lat,
    } satisfies PeakFeatureProperties,
  })),
};
