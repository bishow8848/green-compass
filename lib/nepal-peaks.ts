/**
 * Named summits, viewpoints and passes across Nepal, drawn on every trek map
 * as a small dot with a hover card.
 *
 * Coordinates are summit points rounded to 4 decimals (~11 m), each one taken
 * from the matching OpenStreetMap node and cross-checked against Wikidata
 * where the two sources or a published figure disagreed. Do not eyeball a new
 * entry onto the map — look up its node, or the dot lands on a neighbouring
 * slope. Heights stay at the value trekkers see published (which is sometimes
 * a little off the DEM-derived figure in OSM); feet are derived from the metre
 * value, so only edit the metres.
 *
 * `kind` separates true summits from the viewpoints and passes trekkers
 * actually walk to, so the map can style and filter them differently.
 */

export type PeakKind = "peak" | "viewpoint" | "pass";

export interface NepalPeak {
  name: string;
  /** Local or alternative name shown under the title in the hover card. */
  altName?: string;
  lng: number;
  lat: number;
  /** Height above sea level, in metres. */
  elevation: number;
  /** Trekking/climbing region the peak belongs to. */
  region: string;
  kind: PeakKind;
  /** One or two lines of context for the hover card. */
  note?: string;
}

